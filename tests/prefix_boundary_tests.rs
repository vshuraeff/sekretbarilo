/// the start boundaries as written in rules.toml: `\b` where the token starts with a literal word
/// byte, the half boundary where it starts with a class. each also admits any source-code escape
/// sequence (`\n`, `\r`, `\t`, `\f`, `\b`, `\v`, octal, `\xHH`, `\uHHHH`, `\UHHHHHHHH`, `\u{...}`,
/// or a bare `\<letter>`), tried longest-form-first so a multi-byte escape is consumed whole.
const WORD_START: &str = r"(?:%[0-9A-Fa-f]{2}|\[[0-9;:]*[mK]|\\(?:u\{[0-9A-Fa-f]{1,6}\}|u[0-9A-Fa-f]{4}|U[0-9A-Fa-f]{8}|x[0-9A-Fa-f]{2}|[0-7]{1,3}|[A-Za-z])|(?-u:\b))";
const CLASS_START: &str = r"(?:%[0-9A-Fa-f]{2}|\[[0-9;:]*[mK]|\\(?:u\{[0-9A-Fa-f]{1,6}\}|u[0-9A-Fa-f]{4}|U[0-9A-Fa-f]{8}|x[0-9A-Fa-f]{2}|[0-7]{1,3}|[A-Za-z])|(?-u:\b{start-half}))";

const B64: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
