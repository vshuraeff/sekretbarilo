//! token-boundary contract of the prefix-anchored rules.
//!
//! a prefix token matches only where a token starts: at the start of the text, after a byte that
//! is not an ascii word byte, or right after a source-code string escape sequence (`\n`, `\r`,
//! `\t`, `\f`, `\b`, `\v`, an octal escape such as `\0` or `\012`, `\xHH`, `\uHHHH`, `\UHHHHHHHH`
//! or `\u{H..HHHHHH}`, and any other `\<letter>` escape), since json- and c-escaped text glues the
//! token to the escape's last byte. the end is left open: a token glued to trailing word bytes is
//! still reported, because recall wins for tier 1. the negative cases plant each token inside a
//! generated base64 run, the shape that made `facebook-access-token` fire on pem bodies; the
//! positive cases put the same token into the contexts real tokens are written in. every opaque
//! value is generated at runtime, and so is the pem armor.

