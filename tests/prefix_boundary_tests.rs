#[test]
fn escape_letter_without_its_backslash_still_blocks_the_match() {
    // `n`, `r` and `t` are ordinary word bytes unless a backslash precedes them.
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        for glue in ["n", "r", "t", "/n"] {
            let line = format!("{}value={glue}{token} end", shape.lead);
            if reported_rules(&line).iter().any(|rule| rule == shape.rule) {
                failures.push(format!("{} after {glue:?}", shape.rule));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "prefix matched after an escape letter:\n{}",
        failures.join("\n")
    );
}

#[test]
fn escape_like_letter_in_a_base64_run_without_backslash_is_not_reported() {
    // `x`, `u`, `U` and an octal digit open one of the new escape alternatives; glued to a
    // base64 run with no preceding backslash they are ordinary word bytes and must not let the
    // token through, the same false-positive shape the pem reproducers guard against.
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        let unbounded = shape.unbounded();
        for glue in ['x', 'u', 'U', '7'] {
            let mut generator = Generator::for_rule(shape.rule, u64::from(glue as u32));
            let mut left = generator.run(B64, 40);
            left.pop();
            left.push(glue);
            let line = format!("{}{left}{token}", shape.lead);
            assert!(
                unbounded.is_match(line.as_bytes()),
                "{}: the unbounded rule does not match after {glue:?}",
                shape.rule
            );
            if reported_rules(&line).iter().any(|rule| rule == shape.rule) {
                failures.push(format!("{} after {glue:?}", shape.rule));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "prefix matched after an escape-like letter with no backslash:\n{}",
        failures.join("\n")
    );
}

