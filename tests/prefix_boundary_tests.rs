/// xorshift64*, seeded per rule so every shape gets its own bytes on every machine and run.
struct Generator(u64);

impl Generator {
    fn for_rule(rule: &str, salt: u64) -> Self {
        // fnv-1a over the rule id
        let seed = rule.bytes().fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
            (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3)
        });
        Self((seed ^ salt) | 1)
    }

    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0 = self.0.wrapping_mul(0x2545_F491_4F6C_DD1D);
        self.0
    }

    fn pick(&mut self, alphabet: &[u8]) -> char {
        char::from(alphabet[(self.next() >> 32) as usize % alphabet.len()])
    }

    fn run(&mut self, alphabet: &[u8], length: usize) -> String {
        (0..length).map(|_| self.pick(alphabet)).collect()
    }

    fn bytes(&mut self, length: usize) -> Vec<u8> {
        (0..length).map(|_| (self.next() >> 56) as u8).collect()
    }
}

impl Shape {
    fn token(&self) -> String {
        let mut generator = Generator::for_rule(self.rule, 0);
        self.parts
            .iter()
            .map(|part| match part {
                Lit(text) => (*text).to_owned(),
                Run(alphabet, length) => generator.run(alphabet, *length),
            })
            .collect()
    }

    /// a word byte of the last run's alphabet: appended to the token it lengthens the run.
    fn continuation(&self) -> char {
        self.parts
            .iter()
            .rev()
            .find_map(|part| match part {
                Run(alphabet, _) => alphabet
                    .iter()
                    .copied()
                    .find(u8::is_ascii_alphanumeric)
                    .map(char::from),
                Lit(_) => None,
            })
            .expect("a shape ends in a generated run")
    }

    fn pattern(&self) -> &'static str {
        &RULES
            .iter()
            .find(|rule| rule.id == self.rule)
            .unwrap_or_else(|| panic!("{} is a default rule", self.rule))
            .regex_pattern
    }

    /// the rule as it was before the boundary: whatever it matches here is what the boundary
    /// removes, so a negative case it does not match would pass for the wrong reason.
    fn unbounded(&self) -> Regex {
        Regex::new(
            &self
                .pattern()
                .replace(WORD_START, "")
                .replace(CLASS_START, ""),
        )
        .expect("the unbounded pattern compiles")
    }
}

fn diff_file(lines: &[&str]) -> DiffFile {
    DiffFile {
        path: FILE_PATH.to_owned(),
        is_new: false,
        is_deleted: false,
        is_renamed: false,
        is_binary: false,
        context: None,
        added_lines: lines
            .iter()
            .enumerate()
            .map(|(index, line)| AddedLine {
                line_number: index + 1,
                content: line.as_bytes().to_vec(),
            })
            .collect(),
    }
}

/// rule ids reported on either surface; values stay out of failure messages.
fn reported_rules(text: &str) -> Vec<String> {
    let lines: Vec<&str> = text.lines().collect();
    let mut rules: Vec<String> = scan(&[diff_file(&lines)], &SCANNER, &ALLOWLIST)
        .into_iter()
        .map(|finding| finding.rule_id)
        .chain(
            scan_text(text, &SCANNER, &ALLOWLIST)
                .into_iter()
                .map(|matched| matched.rule_id),
        )
        .collect();
    rules.sort();
    rules.dedup();
    rules
}

fn armor(edge: &str) -> String {
    let dashes = "-".repeat(5);
    format!("{dashes}{edge} PRIVATE KEY{dashes}")
}

fn base64(bytes: &[u8]) -> String {
    let mut encoded = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let word = chunk
            .iter()
            .enumerate()
            .fold(0_u32, |word, (index, &byte)| {
                word | (u32::from(byte) << (16 - 8 * index))
            });
        for index in 0..4 {
            if index <= chunk.len() {
                encoded.push(char::from(B64[((word >> (18 - 6 * index)) & 63) as usize]));
            } else {
                encoded.push('=');
            }
        }
    }
    encoded
}

fn pem_block(body: &[String]) -> String {
    let mut lines = vec![armor("BEGIN")];
    lines.extend(body.iter().cloned());
    lines.push(armor("END"));
    lines.join("\n")
}

/// `token` inside a base64 run: `before` random bytes, then the token, then `after` random bytes.
/// the bytes touching the token are forced alphanumeric, since `+` and `/` are boundaries.
fn planted(generator: &mut Generator, token: &str, before: usize, after: usize) -> String {
    let mut left = generator.run(B64, before);
    left.pop();
    left.push(generator.pick(ALNUM));
    let mut right = generator.pick(ALNUM).to_string();
    right.push_str(&generator.run(B64, after.saturating_sub(1)));
    format!("{left}{token}{right}")
}

#[test]
fn every_boundary_rule_has_a_shape() {
    let guarded: Vec<&str> = RULES
        .iter()
        .filter(|rule| {
            rule.regex_pattern.contains(WORD_START) || rule.regex_pattern.contains(CLASS_START)
        })
        .map(|rule| rule.id.as_str())
        .collect();
    let shaped: Vec<&str> = SHAPES.iter().map(|shape| shape.rule).collect();
    let missing: Vec<&&str> = guarded.iter().filter(|id| !shaped.contains(id)).collect();
    let unguarded: Vec<&&str> = shaped.iter().filter(|id| !guarded.contains(id)).collect();
    assert!(missing.is_empty(), "rules without a shape: {missing:?}");
    assert!(
        unguarded.is_empty(),
        "shapes whose rule has no start boundary: {unguarded:?}"
    );
}

#[test]
fn prefix_inside_a_wrapped_pem_body_is_not_reported() {
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        let unbounded = shape.unbounded();
        for column in [1, 7, 21] {
            let mut generator = Generator::for_rule(shape.rule, column as u64);
            let tail = 64_usize.saturating_sub(column + token.len()).max(8);
            let line = format!(
                "{}{}",
                shape.lead,
                planted(&mut generator, &token, column, tail)
            );
            assert!(
                unbounded.is_match(line.as_bytes()),
                "{} at column {column}: the unbounded rule does not match the planted line",
                shape.rule
            );
            let body = vec![
                generator.run(B64, 64),
                line,
                generator.run(B64, 64),
                generator.run(B64, 42) + "==",
            ];
            let rules = reported_rules(&pem_block(&body));
            if rules.iter().any(|rule| rule == shape.rule) {
                failures.push(format!("{} at column {column}", shape.rule));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "prefix matched mid-run:\n{}",
        failures.join("\n")
    );
}

#[test]
fn prefix_inside_an_unwrapped_base64_line_is_not_reported() {
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        let mut generator = Generator::for_rule(shape.rule, 0x0b64);
        let line = format!(
            "{}{}",
            shape.lead,
            planted(&mut generator, &token, 300, 300)
        );
        assert!(
            shape.unbounded().is_match(line.as_bytes()),
            "{}: the unbounded rule does not match the planted line",
            shape.rule
        );
        if reported_rules(&line).iter().any(|rule| rule == shape.rule) {
            failures.push(shape.rule);
        }
    }
    assert!(failures.is_empty(), "prefix matched mid-run: {failures:?}");
}

#[test]
fn word_byte_before_the_prefix_blocks_the_match() {
    // the right side is a delimiter, so only the start boundary can reject these.
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        let mut generator = Generator::for_rule(shape.rule, 0x1eff);
        for glue in [generator.pick(ALNUM), '_'] {
            let line = format!("{}value={glue}{token} end", shape.lead);
            assert!(
                shape.unbounded().is_match(line.as_bytes()),
                "{}: the unbounded rule does not match",
                shape.rule
            );
            if reported_rules(&line).iter().any(|rule| rule == shape.rule) {
                failures.push(format!("{} after {glue:?}", shape.rule));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "prefix matched after a word byte:\n{}",
        failures.join("\n")
    );
}

#[test]
fn token_glued_to_trailing_word_bytes_is_still_reported() {
    // the end is left open on purpose: a real-length token that runs on into word bytes is
    // reported from its first byte, whole or as its real-length head, never dropped.
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        let line = format!("{}value={token}{} end", shape.lead, shape.continuation());
        let start = shape.lead.len() + "value=".len();
        let on_diff = scan(&[diff_file(&[line.as_str()])], &SCANNER, &ALLOWLIST)
            .iter()
            .any(|finding| {
                finding.rule_id == shape.rule && finding.matched_value.starts_with(token.as_bytes())
            });
        let on_text = scan_text(&line, &SCANNER, &ALLOWLIST)
            .iter()
            .any(|matched| {
                matched.rule_id == shape.rule
                    && matched.range.start == start
                    && matched.range.end >= start + token.len()
            });
        if !on_diff || !on_text {
            failures.push(format!("{}: diff={on_diff} text={on_text}", shape.rule));
        }
    }
    assert!(
        failures.is_empty(),
        "glued token not reported:\n{}",
        failures.join("\n")
    );
}

/// json and c string contexts; `<esc>` is the escape before the token, `<token>` the token.
const ESCAPED_CONTEXTS: &[&str] = &[
    r#"{"level":"info","msg":"session opened<esc><token>\nnext"}"#,
    r#"fprintf(log, "credential:<esc><token>\n");"#,
];

/// every escape shape the start boundary must admit: the three whitespace letters, three more
/// single-letter c escapes, an octal escape of one and of three digits, a two-hex-digit `\x`
/// escape, a 4-hex `\u`, an 8-hex `\U`, and the brace form `\u{...}`.
const STRING_ESCAPES: &[&str] = &[
    r"\n",
    r"\r",
    r"\t",
    r"\f",
    r"\b",
    r"\v",
    r"\0",
    r"\012",
    r"\x20",
    r"\u000a",
    r"\U0000000a",
    r"\u{a}",
];

#[test]
fn token_after_a_string_escape_is_reported() {
    // an escape's last byte is a word byte, so without the escape alternative the start boundary
    // would reject every token that opens an escaped line.
    let mut failures = Vec::new();
    for shape in SHAPES {
        let token = shape.token();
        for escape in STRING_ESCAPES.iter().copied() {
            for context in ESCAPED_CONTEXTS {
                let (before, after) = context
                    .split_once("<token>")
                    .expect("a context carries a token placeholder");
                let before = format!("{}{}", shape.lead, before.replace("<esc>", escape));
                let line = format!("{before}{token}{after}");
                let span: Range<usize> = before.len()..before.len() + token.len();
                let on_diff = scan(&[diff_file(&[line.as_str()])], &SCANNER, &ALLOWLIST)
                    .iter()
                    .any(|finding| {
                        finding.rule_id == shape.rule && finding.matched_value == token.as_bytes()
                    });
                let on_text = scan_text(&line, &SCANNER, &ALLOWLIST)
                    .iter()
                    .any(|matched| matched.rule_id == shape.rule && matched.range == span);
                let redacted = !redact_text(&line, &SCANNER, &ALLOWLIST).contains(&token);
                if !on_diff || !on_text || !redacted {
                    failures.push(format!(
                        "{} after {escape} in `{context}`: diff={on_diff} text={on_text} \
                         redacted={redacted}",
                        shape.rule
                    ));
                }
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} escaped context(s) lost:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

