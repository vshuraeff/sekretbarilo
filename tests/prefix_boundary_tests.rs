/// the pkcs#8 envelope of an rsa-2048 key up to the modulus: sequence, version, rsaEncryption
/// algorithm identifier, octet string, then the inner sequence with its version 0 and the modulus
/// integer header. its bytes `02 01 00 02 82` encode to `AgEAAoIB`, so every such key carries
/// `EAA` inside a base64 run at a fixed column of its first body line.
const PKCS8_RSA_ENVELOPE: &[u8] = &[
    0x30, 0x82, 0x04, 0xbd, 0x02, 0x01, 0x00, 0x30, 0x0d, 0x06, 0x09, 0x2a, 0x86, 0x48, 0x86, 0xf7,
    0x0d, 0x01, 0x01, 0x01, 0x05, 0x00, 0x04, 0x82, 0x04, 0xa7, 0x30, 0x82, 0x04, 0xa3, 0x02, 0x01,
    0x00, 0x02, 0x82, 0x01, 0x01, 0x00,
];

#[test]
fn pkcs8_rsa_body_does_not_report_a_facebook_token() {
    let facebook = SHAPES
        .iter()
        .find(|shape| shape.rule == "facebook-access-token")
        .expect("facebook shape");
    let mut der = PKCS8_RSA_ENVELOPE.to_vec();
    der.extend(Generator::for_rule(facebook.rule, 0x5130).bytes(1152));
    let encoded = base64(&der);
    assert_eq!(
        &encoded[40..48],
        "AgEAAoIB",
        "the envelope places EAA mid-run"
    );
    // unwrapped, the run after that `EAA` is long enough for the old rule: the reported shape.
    assert_eq!(
        facebook
            .unbounded()
            .find_at(encoded.as_bytes(), 42)
            .map(|matched| matched.start()),
        Some(42),
        "the unbounded rule does not match the envelope's EAA"
    );
    let wrapped: Vec<String> = encoded
        .as_bytes()
        .chunks(64)
        .map(|chunk| String::from_utf8_lossy(chunk).into_owned())
        .collect();
    for text in [encoded.clone(), pem_block(&wrapped)] {
        let rules = reported_rules(&text);
        assert!(
            !rules.iter().any(|rule| rule == facebook.rule),
            "facebook-access-token reported on a pkcs#8 body: {rules:?}"
        );
    }
}
