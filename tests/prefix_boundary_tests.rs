const DIGIT: &[u8] = b"0123456789";

enum Part {
    Lit(&'static str),
    /// generated bytes from an alphabet; a bounded rule's last run is generated at its maximum
    /// length, so one more byte of the alphabet makes the token too long.
    Run(&'static [u8], usize),
}

use Part::{Lit, Run};

struct Shape {
    rule: &'static str,
    /// context a key-anchored rule needs on the same line.
    lead: &'static str,
    parts: &'static [Part],
}

const fn shape(rule: &'static str, parts: &'static [Part]) -> Shape {
    Shape {
        rule,
        lead: "",
        parts,
    }
}

